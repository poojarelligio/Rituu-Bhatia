"use client";

import { motion, useReducedMotion } from "framer-motion";

/**
 * Tiny scroll-reveal wrapper so server-rendered pages (About, Services...)
 * can fade content in without becoming client components themselves.
 * Place in: src/components/ui/Reveal.tsx
 */
export default function Reveal({
  children,
  delay = 0,
  y = 28,
  className,
}: {
  children: React.ReactNode;
  delay?: number;
  y?: number;
  className?: string;
}) {
  const reduce = useReducedMotion();
  return (
    <motion.div
      className={className}
      initial={reduce ? false : { opacity: 0, y }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-80px" }}
      transition={{ duration: 0.8, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}